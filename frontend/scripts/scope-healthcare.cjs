// Builds src/styles/scoped-healthcare.css, the stylesheet for the screens the legacy host still
// renders inside React (#legacy-root): sign-in, registration, activation and the admin workspace.
// Every rule in legacy-host.css is prefixed with #legacy-root so it cannot leak into React pages;
// template-healthcare.css is appended as is. Run with `npm run css` (dev and build do it for you).
const fs=require('fs'),postcss=require('../node_modules/postcss');
const styles=__dirname+'/../src/styles/';
const root=postcss.parse(fs.readFileSync(styles+'legacy-host.css','utf8'));
root.walkRules(rule=>{
 let parent=rule.parent;while(parent){if(parent.type==='atrule'&&parent.name.endsWith('keyframes'))return;parent=parent.parent;}
 rule.selector=rule.selector.split(/,(?![^()]*\))/).map(s=>{s=s.trim();if(s===':root'||s==='html'||s==='body'||s==='html body')return '#legacy-root';if(s.includes(':root'))return s.replaceAll(':root','#legacy-root');return '#legacy-root '+s.replace(/^html\s+|^body\s+/,'');}).join(', ');
});
fs.writeFileSync(styles+'scoped-healthcare.css','/* GENERATED by scripts/scope-healthcare.cjs from legacy-host.css + template-healthcare.css. Do not edit; run npm run css. */\n'+root.toString()+'\n'+fs.readFileSync(styles+'template-healthcare.css','utf8'));
