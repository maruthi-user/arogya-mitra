-- One row per signed-in device. The access token carries the session id; every request checks the row is still
-- active, so revoking it (logout, password change, deactivation) takes effect at once.
-- Only SHA-256 hashes of refresh tokens are stored.
CREATE TABLE USER_SESSIONS (
    ID                  VARCHAR(36)  PRIMARY KEY,
    USER_ID             BIGINT       NOT NULL,
    REFRESH_TOKEN_HASH  VARCHAR(64)  NOT NULL,
    PREVIOUS_TOKEN_HASH VARCHAR(64),
    ROTATED_AT          TIMESTAMP(6),
    IP_ADDRESS          VARCHAR(64),
    USER_AGENT          VARCHAR(300),
    CREATED_AT          TIMESTAMP(6) NOT NULL,
    LAST_SEEN_AT        TIMESTAMP(6) NOT NULL,
    EXPIRES_AT          TIMESTAMP(6) NOT NULL,
    ABSOLUTE_EXPIRES_AT TIMESTAMP(6) NOT NULL,
    REVOKED_AT          TIMESTAMP(6),
    REVOKE_REASON       VARCHAR(40),
    CONSTRAINT UK_SESSION_REFRESH_HASH UNIQUE (REFRESH_TOKEN_HASH),
    CONSTRAINT FK_SESSION_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_SESSION_USER ON USER_SESSIONS (USER_ID, REVOKED_AT);
CREATE INDEX IDX_SESSION_PREVIOUS_HASH ON USER_SESSIONS (PREVIOUS_TOKEN_HASH);
CREATE INDEX IDX_SESSION_EXPIRES ON USER_SESSIONS (EXPIRES_AT);
