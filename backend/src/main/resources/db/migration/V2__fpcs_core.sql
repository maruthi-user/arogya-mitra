-- Baseline: the schema the template had when it still used ddl-auto=update.
-- IF NOT EXISTS everywhere, so it is safe on a database an older template version already created
-- (ddl-auto=update, or the multi-module template whose platform/V0_x history is ignored, see
-- spring.flyway.ignore-migration-patterns): existing tables are kept with their data, missing ones are added.
-- Never edit a migration once it has run anywhere: add a new V<n>__*.sql.
-- Tables of optional modules are created even when the module is switched off; they stay empty.

CREATE TABLE IF NOT EXISTS APP_USERS (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL           VARCHAR(150) NOT NULL,
    PASSWORD        VARCHAR(255) NOT NULL,
    USERNAME        VARCHAR(50)  NOT NULL,
    ROLE            VARCHAR(50)  NOT NULL,
    STATUS          VARCHAR(20)  NOT NULL,
    FAILED_ATTEMPTS INTEGER      NOT NULL,
    LAST_LOGIN_AT   TIMESTAMP(6),
    CREATED_AT      TIMESTAMP(6),
    UPDATED_AT      TIMESTAMP(6),
    CONSTRAINT UK_APP_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_APP_USERS_USERNAME UNIQUE (USERNAME)
);

-- audit module
CREATE TABLE IF NOT EXISTS AUDIT_LOGS (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENTITY_TYPE VARCHAR(80)  NOT NULL,
    ENTITY_ID   VARCHAR(80)  NOT NULL,
    ACTION      VARCHAR(60)  NOT NULL,
    ACTOR_ID    BIGINT,
    ACTOR_NAME  VARCHAR(150),
    DETAILS     TEXT,
    CREATED_AT  TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_ENTITY ON AUDIT_LOGS (ENTITY_TYPE, ENTITY_ID);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_ACTOR ON AUDIT_LOGS (ACTOR_ID);
CREATE INDEX IF NOT EXISTS IDX_AUDIT_CREATED ON AUDIT_LOGS (CREATED_AT);

-- files module
CREATE TABLE IF NOT EXISTS FILE_ATTACHMENTS (
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER_TYPE   VARCHAR(60)  NOT NULL,
    OWNER_ID     VARCHAR(60)  NOT NULL,
    FILE_NAME    VARCHAR(255) NOT NULL,
    CONTENT_TYPE VARCHAR(150),
    SIZE_BYTES   BIGINT       NOT NULL,
    STORAGE_KEY  VARCHAR(300) NOT NULL,
    UPLOADED_BY  BIGINT,
    CREATED_AT   TIMESTAMP(6)
);
CREATE INDEX IF NOT EXISTS IDX_ATTACH_OWNER ON FILE_ATTACHMENTS (OWNER_TYPE, OWNER_ID);

-- passwordreset module
CREATE TABLE IF NOT EXISTS PASSWORD_RESET_TOKENS (
    ID         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID    BIGINT       NOT NULL,
    TOKEN_HASH VARCHAR(64)  NOT NULL,
    EXPIRES_AT TIMESTAMP(6) NOT NULL,
    USED_AT    TIMESTAMP(6),
    CREATED_AT TIMESTAMP(6),
    CONSTRAINT UK_PRT_TOKEN_HASH UNIQUE (TOKEN_HASH)
);
CREATE INDEX IF NOT EXISTS IDX_PRT_USER ON PASSWORD_RESET_TOKENS (USER_ID, CREATED_AT);
